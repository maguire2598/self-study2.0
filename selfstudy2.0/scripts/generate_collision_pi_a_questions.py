def rotate(values: list[str], offset: int) -> list[str]:
    offset %= len(values)
    return values[offset:] + values[:offset]


def choice_options(correct: list[str], wrong: list[str], offset: int):
    tagged = [(text, True) for text in correct] + [(text, False) for text in wrong]
    tagged = rotate(tagged, offset)
    options = [{"id": OPTION_IDS[i], "text": text} for i, (text, _) in enumerate(tagged)]
    answers = [OPTION_IDS[i] for i, (_, is_correct) in enumerate(tagged) if is_correct]
    return options, answers


def make_questions(spec: tuple, node_index: int) -> list[dict]:
    node_id, title, facts, misconceptions, fill_prompt, blank_answers = spec
    slug = node_id.lower().replace(".", "-")
    questions = []
    single_prompts = [
        f"关于“{title}”，下列哪项表述最准确？",
        f"在本课程的理想碰撞模型中，判断“{title}”时应采用哪项依据？",
        f"下列哪项最符合“{title}”的操作约定或适用边界？",
    ]
    for index in range(3):
        correct = facts[index]
        wrong = rotate(misconceptions, index)
        options, answers = choice_options([correct], wrong, node_index + index)
        questions.append({
            "id": f"cp-{slug}-sc-{index + 1:02d}",
            "node_id": node_id,
            "node_title": title,
            "question_type": "single_choice",
            "assessment_kind": "objective",
            "difficulty": index + 1,
            "prompt": single_prompts[index],
            "options": options,
            "correct_answers": answers,
            "explanation": f"判断依据：{correct}",
            "enabled": True,
            "revision": 0,
            "author_notes": "",
        })

    multiple_sets = [
        ([facts[0], facts[1]], [misconceptions[0], misconceptions[1]]),
        ([facts[1], facts[2]], [misconceptions[1], misconceptions[2]]),
    ]
    multiple_prompts = [
        f"关于“{title}”，以下哪些属于需要掌握的核心事实？（选择两项）",
        f"判断“{title}”的条件、过程或边界时，以下哪些表述成立？（选择两项）",
    ]
    for index, (correct, wrong) in enumerate(multiple_sets):
        options, answers = choice_options(correct, wrong, node_index + index + 1)
        questions.append({
            "id": f"cp-{slug}-mc-{index + 1:02d}",
            "node_id": node_id,
            "node_title": title,
            "question_type": "multiple_choice",
            "assessment_kind": "objective",
            "difficulty": index + 2,
            "prompt": multiple_prompts[index],
            "options": options,
            "correct_answers": answers,
            "explanation": "成立的两项是：" + "；".join(correct),
            "enabled": True,
            "revision": 0,
            "author_notes": "",
        })

    questions.append({
        "id": f"cp-{slug}-mb-01",
        "node_id": node_id,
        "node_title": title,
        "question_type": "multi_blank",
        "assessment_kind": "objective",
        "difficulty": 3,
        "prompt": fill_prompt,
        "blanks": [
            {"id": f"blank_{index + 1}", "accepted_answers": answers}
            for index, answers in enumerate(blank_answers)
        ],
        "explanation": "参考填法：" + "；".join(answers[0] for answers in blank_answers),
        "enabled": True,
        "revision": 0,
        "author_notes": "",
    })
    return questions


def build_bank() -> dict:
    questions = []
    for node_index, spec in enumerate(NODE_SPECS):
        questions.extend(make_questions(spec, node_index))
    return {
        "$schema": "../../../schemas/objective_question_bank.schema.json",
        "course_id": "collision-pi",
        "section_id": "A",
        "title": "碰撞与π · A板块客观题库",
        "version": "1.0.0",
        "distribution_per_node": {
            "single_choice": 3,
            "multiple_choice": 2,
            "multi_blank": 1,
        },
        "delivery_policy": {
            "reveal_answer_after_wrong": False,
            "wrong_answer_action": "error_followup_agent",
            "correct_answer_actions": ["next_question", "error_followup_agent"],
        },
        "status_assessment": {
            "enabled": False,
            "note": "按当前产品决定暂缓设计和生成。",
        },
        "questions": questions,
    }


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(build_bank(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"generated {len(build_bank()['questions'])} questions -> {OUTPUT}")


if __name__ == "__main__":
    main()
